/** Columns of a character: array of 5-element 0/1 arrays (top to bottom). */
export function glyphColumns(ch) {
  const rows = ROWS[ch.toUpperCase()] || ROWS['?'];
  const width = rows[0].length;
  const cols = [];
  for (let c = 0; c < width; c++) cols.push(rows.map((row) => Number(row[c])));
  return cols;
}

/** Columns for a whole string with one blank column between characters. */
export function textColumns(text) {
  const cols = [];
  for (const ch of String(text)) {
    cols.push(...glyphColumns(ch));
    cols.push([0, 0, 0, 0, 0]);
  }
  return cols;
}

/** A single character centred on the 5x5 matrix as a 25-element brightness array. */
export function charMatrix(ch) {
  const cols = glyphColumns(ch);
  const offset = Math.floor((5 - cols.length) / 2);
  const m = new Array(25).fill(0);
  cols.forEach((col, c) => col.forEach((bit, r) => { if (bit) m[r * 5 + offset + c] = 9; }));
  return m;
}
