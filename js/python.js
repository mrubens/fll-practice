const INDENT = '    ';
const pyStr = (s) => JSON.stringify(String(s ?? ''));

export function compileToPython(workspace, robotConfig) {
  const tops = workspace.getTopBlocks(true).filter((b) => !b.isShadow() && b.type.startsWith('flipperevents_when'));
  const out = [];
  const tasks = [];
  const warnings = new Set();
  const ctx = { warnings, counter: 0 };

  tops.forEach((hat, i) => {
    const name = `stack_${i + 1}`;
    const body = compileStack(hat.getNextBlock(), ctx, 1);
    const lines = [`async def ${name}():`];
    const bodyLines = body.length ? body : [INDENT + 'pass'];
    switch (hat.type) {
      case 'flipperevents_whenProgramStarts':
        lines.push(...bodyLines);
        break;
      case 'flipperevents_whenButton': {
        const side = hat.getFieldValue('BUTTON'), ev = hat.getFieldValue('EVENT');
        lines.push(`${INDENT}while True:`);
        lines.push(`${INDENT}${INDENT}await wait_edge(lambda: is_button(${pyStr(side)}, ${pyStr(ev)}))`);
        lines.push(...body.map((l) => INDENT + INDENT + l.slice(INDENT.length)).concat(body.length ? [] : [INDENT + INDENT + 'pass']));
        break;
      }
      default: {
        const pred = hatPredicate(hat, ctx);
        lines.push(`${INDENT}while True:`);
        lines.push(`${INDENT}${INDENT}await wait_edge(lambda: ${pred})`);
        lines.push(...body.map((l) => INDENT + INDENT + l.slice(INDENT.length)).concat(body.length ? [] : [INDENT + INDENT + 'pass']));
      }
    }
    out.push(lines.join('\n'));
    tasks.push(name);
  });

  const cfg = robotConfig || { left: 'A', right: 'B' };
  const header = HELPERS +
    `\nstate['pair'] = (${pyStr(cfg.left)}, ${pyStr(cfg.right)})\n` +
    `motor_pair.pair(motor_pair.PAIR_1, PORTS[${pyStr(cfg.left)}], PORTS[${pyStr(cfg.right)}])\n`;
  const footer = tasks.length ? `\nrunloop.run(${tasks.map((t) => t + '()').join(', ')})\n` : '\n# No "when ..." hat blocks found.\n';
  return { code: header + '\n' + out.join('\n\n') + '\n' + footer, warnings: [...warnings] };
}

function hatPredicate(hat, ctx) {
  switch (hat.type) {
    case 'flipperevents_whenCondition': return bool(hat, 'CONDITION', ctx);
    case 'flipperevents_whenTimer': return `timer() > ${num(hat, 'VALUE', ctx)}`;
    case 'flipperevents_whenColor': return `color_code(${str(hat, 'PORT', ctx)}) == int(${num(hat, 'OPTION', ctx)})`;
    case 'flipperevents_whenDistance':
      return `dist_test(${str(hat, 'PORT', ctx)}, ${pyStr(hat.getFieldValue('COMPARATOR'))}, ${num(hat, 'VALUE', ctx)}, ${pyStr(hat.getFieldValue('UNIT'))})`;
    default:
      ctx.warnings.add(`${hat.type} is not supported in Python export.`);
      return 'False';
  }
}

function compileStack(block, ctx, depth) {
  const lines = [];
  const ind = INDENT.repeat(depth);
  while (block) {
    const gen = STATEMENTS[block.type];
    if (gen) {
      const res = gen(block, ctx, depth);
      for (const l of Array.isArray(res) ? res : [res]) lines.push(ind + l);
    } else {
      ctx.warnings.add(`"${block.type}" has no Python equivalent and was skipped.`);
      lines.push(`${ind}pass  # unsupported: ${block.type}`);
    }
    block = block.getNextBlock();
  }
  return lines;
}

function substack(block, name, ctx, depth) {
  const lines = compileStack(block.getInputTargetBlock(name), ctx, depth);
  return lines.length ? lines : [INDENT.repeat(depth) + 'pass'];
}

// ---- expressions ----
function value(block, name, ctx) {
  const t = block.getInputTargetBlock(name);
  if (!t) return null;
  return expr(t, ctx);
}
function num(block, name, ctx) { const v = value(block, name, ctx); return v === null ? '0' : `num(${v})`; }
function str(block, name, ctx) { const v = value(block, name, ctx); return v === null ? '""' : `str(${v})`; }
function bool(block, name, ctx) { const v = value(block, name, ctx); return v === null ? 'False' : `truthy(${v})`; }

function expr(b, ctx) {
  switch (b.type) {
    case 'math_number': case 'math_positive_number': case 'math_whole_number': {
      const n = Number(b.getFieldValue('NUM'));
      return Number.isFinite(n) ? String(n) : '0';
    }
    case 'text': return pyStr(b.getFieldValue('TEXT'));
    case 'data_variable': return `v.get(${pyStr(varName(b))}, 0)`;
  }
  if (SELECTORS[b.type]) {
    const val = b.getFieldValue('field_' + b.type);
    return typeof val === 'number' ? String(val) : pyStr(val);
  }
  const gen = REPORTERS[b.type];
  if (gen) return gen(b, ctx);
  ctx.warnings.add(`"${b.type}" has no Python equivalent; using 0.`);
  return '0';
}

function varName(b) { const f = b.getField('VARIABLE'); return f ? f.getText() : 'variable'; }

