// Add "import math" when needed.
const _compile = compileToPython;
export function compile(workspace, robotConfig) {
  const res = _compile(workspace, robotConfig);
  if (res.code.includes('math.')) res.code = res.code.replace('import runloop, motor,', 'import math, runloop, motor,');
  return res;
}
